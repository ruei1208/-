export function tr(s) {
  if (LANG !== 'en' || typeof s !== 'string' || !/[　-鿿＀-￯]/.test(s)) return s;
  if (EN[s] != null) return EN[s];
  let m;
  if ((m = s.match(/^資料來源：(.*)$/))) return 'Source: ' + tr(m[1]);
  if ((m = s.match(/^懸停 (\S+) cm$/))) return `Hover ${m[1]} cm`;
  if ((m = s.match(/^> (.*)$/))) return '> ' + tr(m[1]);
  // citation lines and other mixed strings: swap the full-width punctuation
  return s.replace(/；/g, '; ').replace(/，/g, ', ').replace(/：/g, ': ');
}
